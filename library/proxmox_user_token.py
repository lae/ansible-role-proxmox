from ansible.module_utils.basic import AnsibleModule
from ansible.module_utils.pvesh import ProxmoxShellError
import ansible.module_utils.pvesh as pvesh

class ProxmoxUserToken(object):
    def __init__(self, module):
        self.module = module
        self.userid = module.params['userid']
        self.tokenid = module.params['tokenid']
        self.state = module.params['state']
        self.comment = module.params['comment']
        self.expire = module.params['expire']
        self.privsep = module.params['privsep']
        self.full_tokenid = "{}!{}".format(self.userid, self.tokenid)
        self.resource = "access/users/{}/token/{}".format(self.userid, self.tokenid)

    def lookup(self):
        # The token list is used rather than the token endpoint, since pvesh
        # doesn't report missing tokens in a way we can map to a 404.
        try:
            tokens = pvesh.get("access/users/{}/token".format(self.userid))
        except ProxmoxShellError as e:
            self.module.fail_json(msg=e.message, status_code=e.status_code)

        # A missing user has no tokens; creation will then fail with a clear
        # error from PVE, while state=absent stays a no-op.
        for token in tokens or []:
            if token['tokenid'] == self.tokenid:
                return token

        return None

    def prepare_token_args(self):
        args = {}

        args['expire'] = self.expire
        args['privsep'] = 1 if self.privsep else 0

        if self.comment is not None:
            args['comment'] = self.comment

        return args

    def remove_token(self):
        try:
            pvesh.delete(self.resource)
            return (True, None)
        except ProxmoxShellError as e:
            return (False, e.message)

    def create_token(self):
        try:
            return (pvesh.create(self.resource, **self.prepare_token_args()), None)
        except ProxmoxShellError as e:
            return (None, e.message)

    def modify_token(self, lookup):
        staged_token = self.prepare_token_args()

        updated_fields = []
        error = None

        for key in staged_token:
            # pvesh may return these as strings, so normalize before comparing
            current = lookup.get(key, 0 if key != 'comment' else None)
            if key != 'comment' and current is not None:
                current = int(current)
            if staged_token[key] != current:
                updated_fields.append(key)

        if self.module.check_mode:
            self.module.exit_json(changed=bool(updated_fields), expected_changes=updated_fields)

        if not updated_fields:
            return (updated_fields, error)

        try:
            pvesh.set(self.resource, **staged_token)
        except ProxmoxShellError as e:
            error = e.message

        return (updated_fields, error)

def main():
    # Refer to https://pve.proxmox.com/pve-docs/api-viewer/index.html
    module = AnsibleModule(
        argument_spec = dict(
            userid=dict(type='str', required=True, aliases=['user']),
            tokenid=dict(type='str', required=True, aliases=['name']),
            state=dict(default='present', choices=['present', 'absent'], type='str'),
            comment=dict(default=None, type='str'),
            expire=dict(default=0, type='int'),
            privsep=dict(default='yes', type='bool'),
        ),
        supports_check_mode=True
    )

    token = ProxmoxUserToken(module)

    changed = False
    error = None
    result = {}
    result['full_tokenid'] = token.full_tokenid
    result['state'] = token.state

    lookup = token.lookup()

    if token.state == 'absent':
        if lookup is not None:
            if module.check_mode:
                module.exit_json(changed=True)

            (changed, error) = token.remove_token()
    elif token.state == 'present':
        if lookup is None:
            if module.check_mode:
                module.exit_json(changed=True)

            (created, error) = token.create_token()
            if error is None:
                changed = True
                result['value'] = created['value']
        else:
            # modify token (note: this function is check mode aware)
            (updated_fields, error) = token.modify_token(lookup)

            if updated_fields:
                changed = True
                result['updated_fields'] = updated_fields

    if error is not None:
        module.fail_json(full_tokenid=token.full_tokenid, msg=error)

    lookup = token.lookup()
    if lookup:
        result['token'] = lookup

    result['changed'] = changed

    module.exit_json(**result)

if __name__ == '__main__':
    main()
